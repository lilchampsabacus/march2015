create or replace function public.staff_official_daily_practice_status(
  p_date date default ((now() at time zone 'Asia/Kolkata')::date)
)
returns table (
  user_id uuid,
  student_name text,
  level integer,
  batch_name text,
  practice_id uuid,
  practice_status text,
  completed_sections text[],
  responses jsonb,
  section_seconds jsonb,
  completed_at timestamptz,
  retry_summary jsonb
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.current_user_is_staff() then
    raise exception 'Staff access required';
  end if;

  return query
  select p.id,
         coalesce(p.full_name, 'Student'),
         p.current_level,
         p.batch_name,
         odp.id,
         coalesce(odp.status, 'not_started'),
         coalesce(odp.completed_sections, '{}'::text[]),
         coalesce(odp.responses, '{}'::jsonb),
         coalesce(odp.section_seconds, '{}'::jsonb),
         odp.completed_at,
         coalesce(r.retry_summary, '[]'::jsonb)
  from public.profiles p
  left join public.official_daily_practice odp
    on odp.user_id = p.id
   and odp.practice_date = p_date
  left join lateral (
    select jsonb_agg(
      jsonb_build_object(
        'section', rr.section,
        'retry_type', rr.retry_type,
        'completed', rr.completed,
        'correct_count', rr.correct_count,
        'wrong_count', rr.wrong_count,
        'skipped_count', rr.skipped_count,
        'duration_seconds', rr.duration_seconds,
        'created_at', rr.created_at,
        'completed_at', rr.completed_at
      ) order by rr.created_at
    ) as retry_summary
    from public.official_daily_practice_retries rr
    where rr.official_daily_practice_id = odp.id
  ) r on true
  where p.role = 'student'
    and p.is_active is true
    and p.student_status = 'active'
    and p.current_level between 2 and 8
  order by lower(coalesce(p.batch_name, '')), p.current_level, lower(coalesce(p.full_name, 'Student'));
end;
$$;

