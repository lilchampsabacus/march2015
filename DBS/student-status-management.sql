create function public.admin_list_student_levels()
returns table (
  id uuid,
  full_name text,
  email text,
  current_level integer,
  batch_name text,
  centre_id smallint,
  centre_name text,
  centre_short_name text,
  is_active boolean,
  student_status text,
  status_changed_at timestamptz,
  status_reason text,
  status_note text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.current_user_is_admin() then
    raise exception 'Admin access required';
  end if;

  return query
  select p.id,
         p.full_name,
         u.email::text,
         p.current_level,
         p.batch_name,
         p.centre_id,
         c.name,
         c.short_name,
         p.is_active,
         p.student_status,
         p.status_changed_at,
         p.status_reason,
         p.status_note,
         p.created_at
  from public.profiles p
  join auth.users u on u.id = p.id
  left join public.centres c on c.id = p.centre_id
  where p.role = 'student'
  order by case p.student_status
             when 'active' then 1
             when 'on_hold' then 2
             when 'not_enrolled' then 3
             when 'passed_out' then 4
             when 'dropped_out' then 5
             else 6
           end,
           coalesce(p.is_active, false) desc,
           c.sort_order nulls first,
           lower(coalesce(p.batch_name, '')),
           lower(coalesce(p.full_name, u.email, ''));
end;
$$;

create or replace function public.admin_update_student_status(
  p_student_id uuid,
  p_new_status text,
  p_reason text,
  p_note text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old_status text;
  v_reason text := nullif(btrim(p_reason), '');
  v_note text := nullif(btrim(p_note), '');
begin
  if not public.current_user_is_admin() then
    raise exception 'Admin access required';
  end if;

  if p_new_status is null or p_new_status not in ('active', 'on_hold', 'dropped_out', 'passed_out', 'not_enrolled') then
    raise exception 'Invalid student status';
  end if;

  if v_reason is null or char_length(v_reason) > 150 then
    raise exception 'A status reason of 1 to 150 characters is required';
  end if;

  if v_note is not null and char_length(v_note) > 500 then
    raise exception 'Status note must be 500 characters or less';
  end if;

  select p.student_status
  into v_old_status
  from public.profiles p
  where p.id = p_student_id and p.role = 'student'
  for update;

  if not found then
    raise exception 'Student not found';
  end if;

  if v_old_status is distinct from p_new_status then
    update public.profiles
    set student_status = p_new_status,
        status_changed_at = now(),
        status_reason = v_reason,
        status_note = v_note
    where id = p_student_id and role = 'student';

    insert into public.student_status_history (
      student_id, old_status, new_status, reason, note, changed_by
    ) values (
      p_student_id, v_old_status, p_new_status, v_reason, v_note, auth.uid()
    );
  end if;
end;
$$;

create or replace function public.admin_bulk_update_student_statuses(
  p_student_ids uuid[],
  p_new_status text,
  p_reason text,
  p_note text default null
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id uuid;
  v_old_status text;
  v_reason text := nullif(btrim(p_reason), '');
  v_note text := nullif(btrim(p_note), '');
  v_count integer := 0;
begin
  if not public.current_user_is_admin() then
    raise exception 'Admin access required';
  end if;

  if p_student_ids is null or array_length(p_student_ids, 1) is null then
    return 0;
  end if;

  if p_new_status is null or p_new_status not in ('active', 'on_hold', 'dropped_out', 'passed_out', 'not_enrolled') then
    raise exception 'Invalid student status';
  end if;

  if v_reason is null or char_length(v_reason) > 150 then
    raise exception 'A status reason of 1 to 150 characters is required';
  end if;

  if v_note is not null and char_length(v_note) > 500 then
    raise exception 'Status note must be 500 characters or less';
  end if;

  foreach v_id in array p_student_ids loop
    select p.student_status
    into v_old_status
    from public.profiles p
    where p.id = v_id and p.role = 'student'
    for update;

    if found and v_old_status is distinct from p_new_status then
      update public.profiles
      set student_status = p_new_status,
          status_changed_at = now(),
          status_reason = v_reason,
          status_note = v_note
      where id = v_id and role = 'student';

      insert into public.student_status_history (
        student_id, old_status, new_status, reason, note, changed_by
      ) values (
        v_id, v_old_status, p_new_status, v_reason, v_note, auth.uid()
      );

      v_count := v_count + 1;
    end if;
  end loop;

  return v_count;
end;
$$;

create or replace function public.admin_recent_status_changes(p_limit integer default 50)
returns table (
  student_id uuid,
  student_name text,
  old_status text,
  new_status text,
  reason text,
  note text,
  changed_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.current_user_is_admin() then
    raise exception 'Admin access required';
  end if;

  return query
  select h.student_id,
         coalesce(nullif(btrim(p.full_name), ''), u.email::text, 'Student'),
         h.old_status,
         h.new_status,
         h.reason,
         h.note,
         h.changed_at
  from public.student_status_history h
  join public.profiles p on p.id = h.student_id
  left join auth.users u on u.id = h.student_id
  order by h.changed_at desc
  limit greatest(1, least(coalesce(p_limit, 50), 200));
end;
$$;

create or replace function public.staff_active_student_practice_overview()
returns table (
  user_id uuid,
  student_name text,
  level integer,
  batch_name text,
  centre_id smallint,
  centre_name text,
  last_practice_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.current_user_is_staff() then
    raise exception 'Staff access required';
  end if;

  return query
  select p.id,
         coalesce(nullif(btrim(p.full_name), ''), 'Student'),
         p.current_level,
