      add constraint profiles_status_reason_length
      check (status_reason is null or char_length(status_reason) <= 150);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'profiles_status_note_length'
      and conrelid = 'public.profiles'::regclass
  ) then
