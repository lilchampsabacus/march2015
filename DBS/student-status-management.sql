create table if not exists public.student_status_history (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  old_status text,
  new_status text not null,
  reason text not null,
  note text,
  changed_by uuid not null references public.profiles(id) on update restrict on delete restrict,
  changed_at timestamptz not null default now(),
  constraint student_status_history_old_status_check
    check (old_status is null or old_status in ('active', 'on_hold', 'dropped_out', 'passed_out', 'not_enrolled')),
  constraint student_status_history_new_status_check
    check (new_status in ('active', 'on_hold', 'dropped_out', 'passed_out', 'not_enrolled')),
  constraint student_status_history_reason_length
    check (char_length(btrim(reason)) between 1 and 150),
  constraint student_status_history_note_length
    check (note is null or char_length(note) <= 500)
);

alter table public.student_status_history enable row level security;

create index if not exists student_status_history_student_changed_idx
  on public.student_status_history (student_id, changed_at desc);

create index if not exists student_status_history_changed_by_idx
  on public.student_status_history (changed_by);

