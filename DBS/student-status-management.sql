create or replace function public.admin_list_centres()
returns table (
  id smallint,
  code text,
  name text,
  short_name text,
  sort_order smallint,
  active_student_count bigint
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.current_user_is_admin() then
    raise exception 'Admin access required';
  end if;

  return query
  select c.id,
         c.code,
         c.name,
         c.short_name,
         c.sort_order,
         count(p.id) filter (
           where p.role = 'student'
             and p.student_status = 'active'
             and p.is_active is true
         )
  from public.centres c
  left join public.profiles p on p.centre_id = c.id
  where c.is_active = true
  group by c.id, c.code, c.name, c.short_name, c.sort_order
  order by c.sort_order, c.name;
end;
$$;

